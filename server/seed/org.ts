// Seeds the starter org once; later edits in the UI are never overwritten
export const seedOrg = (db: Database.Database) => {
  if (db.prepare('SELECT 1 FROM teams LIMIT 1').get()) return
  const now = new Date().toISOString()
  const insertTeam = db.prepare(
    'INSERT INTO teams (id, name, description, sort, created_at) VALUES (?, ?, ?, ?, ?)',
  )
  const insertRole = db.prepare(`
    INSERT INTO roles (id, team_id, title, description, model, tools, skills, is_lead, prompt, sort, created_at, updated_at)
    VALUES (@id, @teamId, @title, @description, @model, @tools, @skills, @isLead, @prompt, @sort, @now, @now)
  `)
  db.transaction(() => {
    SEED_TEAMS.forEach((team, teamIndex) => {
      insertTeam.run(team.id, team.name, team.description, teamIndex, now)
      team.roles.forEach((role, roleIndex) => {
        insertRole.run({
          id: role.id,
          teamId: team.id,
          title: role.title,
          description: role.description,
          model: role.model,
          tools: JSON.stringify(role.tools),
          skills: JSON.stringify(role.skills ?? []),
          isLead: role.lead ? 1 : 0,
          prompt: role.prompt,
          sort: roleIndex,
          now,
        })
      })
    })
    db.prepare('INSERT OR IGNORE INTO org_settings (key, value) VALUES (?, ?)').run(
      'common_rules',
      DEFAULT_COMMON_RULES,
    )
  })()
}
